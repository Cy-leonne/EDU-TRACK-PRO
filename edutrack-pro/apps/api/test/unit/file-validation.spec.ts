import { BadRequestException } from '@nestjs/common';
import { validateUpload } from '../../src/common/storage/file-validation';

const pdfBytes = Buffer.concat([Buffer.from('%PDF-1.4\n'), Buffer.from('1 0 obj\n<<>>\nendobj\ntrailer\n<<>>\n%%EOF')]);
const jpegBytes = Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xe0]), Buffer.alloc(64, 7)]);
const pngBytes = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.alloc(64, 9)]);

function upload(name: string, mimetype: string, buffer: Buffer) {
  return { originalname: name, mimetype, size: buffer.length, buffer };
}

describe('Upload validation (unit)', () => {
  it('accepts a real PDF', () => {
    const result = validateUpload(upload('notes.pdf', 'application/pdf', pdfBytes));
    expect(result.detectedMime).toBe('application/pdf');
    expect(result.extension).toBe('pdf');
  });

  it('accepts JPEG and PNG images (camera uploads from the mobile app)', () => {
    expect(validateUpload(upload('photo.jpg', 'image/jpeg', jpegBytes)).detectedMime).toBe('image/jpeg');
    expect(validateUpload(upload('scan.png', 'image/png', pngBytes)).detectedMime).toBe('image/png');
  });

  it('rejects an executable disguised with a document extension', () => {
    const elf = Buffer.concat([Buffer.from([0x7f, 0x45, 0x4c, 0x46]), Buffer.alloc(64, 0)]);
    expect(() => validateUpload(upload('homework.pdf', 'application/pdf', elf))).toThrow(BadRequestException);
  });

  it('rejects a script extension outright', () => {
    expect(() => validateUpload(upload('payload.sh', 'text/plain', Buffer.from('rm -rf /')))).toThrow(BadRequestException);
    expect(() => validateUpload(upload('page.html', 'text/html', Buffer.from('<script>alert(1)</script>')))).toThrow(BadRequestException);
  });

  it('rejects a type that is not on the allow-list', () => {
    const video = Buffer.concat([Buffer.from([0x00, 0x00, 0x00, 0x18]), Buffer.from('ftypmp42')]);
    expect(() => validateUpload(upload('clip.mp4', 'video/mp4', video))).toThrow(BadRequestException);
  });

  it('rejects a file whose declared MIME type contradicts its contents', () => {
    expect(() => validateUpload(upload('photo.png', 'image/png', jpegBytes))).toThrow(BadRequestException);
  });

  it('rejects files above the configured size limit', () => {
    const big = Buffer.concat([Buffer.from('%PDF-1.4'), Buffer.alloc(2_000_000, 0x20)]);
    expect(() => validateUpload(upload('big.pdf', 'application/pdf', big), 1_000_000)).toThrow(BadRequestException);
  });

  it('rejects empty uploads', () => {
    expect(() => validateUpload(upload('empty.pdf', 'application/pdf', Buffer.alloc(0)))).toThrow(BadRequestException);
  });

  it('sanitises the display name and never lets it become a storage path', () => {
    const result = validateUpload(upload('../../etc/pa ss wd.pdf', 'application/pdf', pdfBytes));
    expect(result.sanitizedName).not.toContain('/');
    expect(result.sanitizedName).not.toContain('\\');
    // Storage keys are generated by StorageService (school id / purpose / date / uuid),
    // so the user-supplied name is metadata only and can never traverse directories.
    expect(result.originalName).toBe('../../etc/pa ss wd.pdf');
    expect(result.sanitizedName.length).toBeLessThanOrEqual(180);
  });
});
